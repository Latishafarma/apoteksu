const SUPABASE_CRUD_GUIDE = `import { createClient } from '@supabase/supabase-js';

export const supabase = createClient(
  import.meta.env.VITE_SUPABASE_URL,
  import.meta.env.VITE_SUPABASE_ANON_KEY
);

// 1. READ & SEARCH Master Obat
export async function fetchMedicines(keyword = '') {
  const query = supabase.from('medicines').select('*').order('name');
  if (keyword) {
    query.or(\`name.ilike.%\${keyword}%,generic_name.ilike.%\${keyword}%\`);
  }
  const { data, error } = await query;
  if (error) throw error;
  return data;
}

// 2. CREATE / UPDATE Harga Berjenjang Obat
export async function upsertMedicine(payload: Record<string, unknown>) {
  const { data, error } = await supabase
    .from('medicines')
    .upsert(payload, { onConflict: 'sku' })
    .select()
    .single();
  if (error) throw error;
  return data;
}

// 3. CREATE Transaksi POS & Potong Stok Otomatis
export async function submitPosTransaction(txPayload: Record<string, unknown>, items: { id: number; nextStock: number }[]) {
  const { data, error } = await supabase.from('transactions').insert(txPayload).select().single();
  if (error) throw error;
  for (const item of items) {
    await supabase.from('medicines').update({ stock_base: item.nextStock }).eq('id', item.id);
  }
  return data;
}

// 4. DELETE Obat / Kategori
export async function deleteMedicineById(id: number) {
  const { error } = await supabase.from('medicines').delete().eq('id', id);
  if (error) throw error;
}`;

export function SupabaseBackupModule({ data, onRefreshData }: SupabaseBackupModuleProps) {
  const [supabaseUrl, setSupabaseUrl] = useState('');
  const [supabaseAnonKey, setSupabaseAnonKey] = useState('');
  const [syncStatus, setSyncStatus] = useState<'idle' | 'checking' | 'connected' | 'error'>('idle');
  const [syncMessage, setSyncMessage] = useState<string>(
    'Database PostgreSQL utama aktif dan tersinkronisasi. Masukkan kredensial Supabase jika ingin mengaktifkan mirror sync ke project Supabase Anda.'
  );
  const [exporting, setExporting] = useState(false);
  const [restoring, setRestoring] = useState(false);
  const [copiedBlock, setCopiedBlock] = useState<'sql' | 'crud' | null>(null);

  const handleCheckAndSyncSupabase = async () => {
    if (!supabaseUrl.trim() || !supabaseAnonKey.trim()) {
      setSyncStatus('error');
      setSyncMessage(
        'Masukkan Supabase Project URL dan Anon Key terlebih dahulu untuk menguji koneksi dan sinkronisasi.'
      );
      return;
    }

    setSyncStatus('checking');
    setSyncMessage('Menghubungi REST API Supabase...');
    try {
      const client = createClient(supabaseUrl.trim(), supabaseAnonKey.trim());
      const { error: pingError } = await client
        .from('medicines')
        .select('id', { count: 'exact', head: true });

      if (pingError) {
        setSyncStatus('error');
        setSyncMessage(
          `Terhubung ke host Supabase, namun tabel belum siap atau RLS memblokir akses: ${pingError.message}. Gunakan skema SQL di bawah ini.`
        );
        return;
      }

      // Perform lightweight upsert sync for master medicines & interactions
      const medRows = data.medicines.map((m) => ({
        sku: m.sku,
        barcode: m.barcode,
        name: m.name,
        generic_name: m.genericName,
        category_name: m.categoryName,
        classification: m.classification,
        hpp: m.hpp,
        price_reguler: m.priceReguler,
        price_klinik: m.priceKlinik,
        price_mitra: m.priceMitra,
        stock_base: m.stockBase,
        icd10_tags: m.icd10Tags,
      }));
      const { error: upsertErr } = await client
        .from('medicines')
        .upsert(medRows, { onConflict: 'sku' });

      if (upsertErr) {
        setSyncStatus('error');
        setSyncMessage(`Koneksi berhasil, gagal sinkronisasi tabel medicines: ${upsertErr.message}`);
        return;
      }

      setSyncStatus('connected');
      setSyncMessage(
        `Sinkronisasi Supabase berhasil! ${medRows.length} data master obat telah disinkronkan pada ${new Date().toLocaleTimeString('id-ID')}.`
      );
    } catch (err: unknown) {
      setSyncStatus('error');
      setSyncMessage(
        err instanceof Error ? err.message : 'Gagal menghubungi endpoint Supabase.'
      );
    }
  };

  const handleExportJson = async () => {
    setExporting(true);
    try {
      const snapshot = await apiRequest<Record<string, unknown>>('/api/backup/export');
      const blob = new Blob([JSON.stringify(snapshot, null, 2)], {
        type: 'application/json',
      });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `latisha-farma-backup-${new Date().toISOString().slice(0, 10)}.json`;
      document.body.appendChild(a);
      a.click();
      a.remove();
      URL.revokeObjectURL(url);
    } finally {
      setExporting(false);
    }
  };

  const handleRestoreFile = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setRestoring(true);
    try {
      const text = await file.text();
      const parsed = JSON.parse(text);
      const res = await apiRequest<{ message: string; restoredCategories: number; restoredInteractions: number }>(
        '/api/backup/restore',
        {
          method: 'POST',
          body: JSON.stringify(parsed),
        }
      );
      await onRefreshData();
      setSyncStatus('connected');
      setSyncMessage(
        `${res.message} (+${res.restoredCategories} kategori, +${res.restoredInteractions} aturan interaksi).`
      );
    } catch (err: unknown) {
      setSyncStatus('error');
      setSyncMessage(err instanceof Error ? err.message : 'File backup JSON tidak valid.');
    } finally {
      setRestoring(false);
      e.target.value = '';
    }
  };

  const copyCode = async (type: 'sql' | 'crud', text: string) => {
    await navigator.clipboard.writeText(text);
    setCopiedBlock(type);
    setTimeout(() => setCopiedBlock(null), 1800);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-4 pb-4 border-b border-slate-200 dark:border-slate-800">
        <div>
          <h2 className="font-display text-xl font-bold text-slate-900 dark:text-white">
            Sinkronisasi Supabase &amp; Manajemen Backup Database
          </h2>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
            Uji status koneksi Supabase · Backup &amp; restore snapshot JSON · Panduan integrasi API CRUD
          </p>
        </div>
      </div>

      {/* Sync & Backup Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Supabase Connection & Sync Card */}
        <div className="lg:col-span-7 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-5 space-y-4">
          <div className="flex items-center justify-between gap-2">
            <div className="flex items-center gap-2 font-display font-semibold text-sm">
              <Database className="w-4 h-4 text-red-600" />
              <span>Konfigurasi &amp; Sinkronisasi Supabase Client</span>
            </div>
            <span
              className={`text-xs font-medium ${
                syncStatus === 'connected'
                  ? 'text-emerald-700 dark:text-emerald-400'
                  : syncStatus === 'error'
                    ? 'text-rose-600 dark:text-rose-400'
                    : 'text-slate-500'
              }`}
            >
              {syncStatus === 'connected'
                ? 'Tersinkronisasi'
                : syncStatus === 'checking'
                  ? 'Memeriksa...'
                  : syncStatus === 'error'
                    ? 'Perlu Perhatian'
                    : 'PostgreSQL Aktif'}
            </span>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
            <div>
              <label className="block font-medium mb-1">Supabase Project URL</label>
              <input
                type="url"
                value={supabaseUrl}
                onChange={(e) => setSupabaseUrl(e.target.value)}
                placeholder="https://xxxx.supabase.co"
                className="w-full px-3 py-2 bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 rounded-lg font-mono"
              />
            </div>
            <div>
              <label className="block font-medium mb-1">Supabase Anon Public Key</label>
              <input
                type="password"
                value={supabaseAnonKey}
                onChange={(e) => setSupabaseAnonKey(e.target.value)}
                placeholder="eyJhbGciOiJIUzI1NiIsInR5cCI6..."
                className="w-full px-3 py-2 bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 rounded-lg font-mono"
              />
            </div>
          </div>

          <div className="p-3 rounded-lg bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 text-xs text-slate-600 dark:text-slate-300">
            {syncMessage}
          </div>

          <div className="flex flex-wrap items-center justify-between gap-3">
            <div className="text-xs text-slate-500 tabular-nums">
              Total Rekam Aktif: {data.medicines.length} Obat · {data.patients.length} Pasien ·{' '}
              {data.transactions.length} Transaksi · {data.drugInteractions.length} Aturan Interaksi
            </div>
            <button
              type="button"
              onClick={handleCheckAndSyncSupabase}
              disabled={syncStatus === 'checking'}
              className="px-4 py-2.5 rounded-xl bg-red-700 hover:bg-red-800 text-white text-xs font-semibold flex items-center gap-2 cursor-pointer disabled:opacity-50"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${syncStatus === 'checking' ? 'animate-spin' : ''}`} />
              <span>Sinkronkan &amp; Cek Koneksi Supabase</span>
            </button>
          </div>
        </div>

        {/* JSON Backup & Restore */}
        <div className="lg:col-span-5 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-5 space-y-4">
          <div className="font-display font-semibold text-sm">
            Manajemen Backup &amp; Restore Data JSON
          </div>
          <p className="text-xs text-slate-500 dark:text-slate-400 leading-relaxed">
            Ekspor seluruh katalog obat, harga berjenjang, profil pasien, transaksi kasir, catatan
            SOAP/DRP, dan aturan interaksi obat ke dalam berkas JSON terstruktur untuk arsip audit
            atau pemulihan cepat.
          </p>

          <div className="space-y-3 pt-1">
            <button
              type="button"
              onClick={handleExportJson}
              disabled={exporting}
              className="w-full py-2.5 px-4 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-semibold flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
            >
              <Download className="w-4 h-4" />
              <span>{exporting ? 'Menyiapkan Snapshot...' : 'Unduh Backup Lengkap (.JSON)'}</span>
            </button>

            <label className="w-full py-2.5 px-4 rounded-xl border border-slate-300 dark:border-slate-700 hover:bg-slate-50 dark:hover:bg-slate-800 text-xs font-medium flex items-center justify-center gap-2 cursor-pointer">
              <Upload className="w-4 h-4 text-red-600" />
              <span>{restoring ? 'Memproses Restore...' : 'Restore Snapshot dari File JSON'}</span>
              <input
                type="file"
                accept=".json,application/json"
                onChange={handleRestoreFile}
                className="hidden"
              />
            </label>
          </div>
        </div>
      </div>

      {/* Developer Implementation Guide for Supabase CRUD */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl overflow-hidden">
          <div className="px-4 py-3 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
            <div className="flex items-center gap-2 font-display font-semibold text-xs">
              <Code2 className="w-4 h-4 text-red-600" />
              <span>1. Skema Tabel PostgreSQL / Supabase</span>
            </div>
            <button
              type="button"
              onClick={() => copyCode('sql', SUPABASE_SQL_SCHEMA)}
              className="text-xs text-red-700 dark:text-red-400 flex items-center gap-1 cursor-pointer"
            >
              {copiedBlock === 'sql' ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copiedBlock === 'sql' ? 'Tersalin' : 'Salin SQL'}</span>
            </button>
          </div>
          <pre className="p-4 text-[11px] font-mono overflow-x-auto bg-slate-950 text-slate-200 leading-relaxed max-h-80">
            {SUPABASE_SQL_SCHEMA}
          </pre>
        </div>

        <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl overflow-hidden">
          <div className="px-4 py-3 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
            <div className="flex items-center gap-2 font-display font-semibold text-xs">
              <Code2 className="w-4 h-4 text-emerald-600" />
              <span>2. Panduan API Client CRUD (@supabase/supabase-js)</span>
            </div>
            <button
              type="button"
              onClick={() => copyCode('crud', SUPABASE_CRUD_GUIDE)}
              className="text-xs text-emerald-700 dark:text-emerald-400 flex items-center gap-1 cursor-pointer"
            >
              {copiedBlock === 'crud' ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copiedBlock === 'crud' ? 'Tersalin' : 'Salin Kode'}</span>
            </button>
          </div>
          <pre className="p-4 text-[11px] font-mono overflow-x-auto bg-slate-950 text-slate-200 leading-relaxed max-h-80">
            {SUPABASE_CRUD_GUIDE}
          </pre>
        </div>
      </div>
    </div>
  );
}
