async function ensureMedicinesSatuanBesarPricing() {
  const allMeds = await db.select().from(medicines);
  for (const med of allMeds) {
    const boxMult = Math.max(1, (med.pcsPerStrip || 1) * (med.stripsPerBox || 1));
    // Convert legacy per-base-unit hna, hpp, and priceMitra to Satuan Besar (Box)
    if (boxMult > 1 && med.hpp <= med.priceReguler * 2) {
      const ppn = Number(med.ppnPercent) || 11;
      const hnaBesar = Math.round(med.hna * boxMult);
      const hppBesar =
        med.hppMode === 'hna_ppn'
          ? Math.round(hnaBesar * (1 + ppn / 100))
          : Math.round(med.hpp * boxMult);
      const marginMitra = Number(med.marginMitra) || 12;
      const priceMitraBesar = Math.round(hppBesar * (1 + marginMitra / 100));
      await db
        .update(medicines)
        .set({
          hna: hnaBesar,
          hpp: hppBesar,
          priceMitra: priceMitraBesar,
        })
        .where(eq(medicines.id, med.id));
    } else if (boxMult === 1) {
      // Ensure 11% PPN relationship between HNA Besar and HPP Besar is exact
      const ppn = Number(med.ppnPercent) || 11;
      const expectedHna = Math.round(med.hpp / (1 + ppn / 100));
      const expectedHpp = Math.round(med.hna * (1 + ppn / 100));
      if (med.hppMode === 'manual' && med.hna !== expectedHna) {
        await db
          .update(medicines)
          .set({ hna: expectedHna })
          .where(eq(medicines.id, med.id));
      } else if (med.hppMode !== 'manual' && med.hpp !== expectedHpp) {
        await db
          .update(medicines)
          .set({ hpp: expectedHpp })
          .where(eq(medicines.id, med.id));
      }
    }
  }
}

